# 31. Compare two numbers using all six comparison operators.
a = 40
b = 30
# Equal To (==)
if a == b:
    print("Equal hai")
else:
    print("Equal nhi hai")
#Not Equal To (!=)
if a != b:
    print("not Equal hai")
else:
    print("num equal hai")
# Greater Than (>)
if a > b:
    print("A badra hai")
else:
    print("A chota hai")
# Less Than (<)
if a < b:
    print("true")
else:
    print("False")
# Greater Than or Equal To (>=)
if a >= b:
    print("true")
else:
    print("false")
# Less Than or Equal To (<=)
if a <= b:
    print("30 badra hai")
else:
    print("40 se badra hai")