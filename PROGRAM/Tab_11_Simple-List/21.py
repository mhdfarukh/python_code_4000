# 21. Write a program to sort a list of student records in descending order using sort(reverse=True).
student = ["Akash","farukh", "Dileep", "suraj", "shivem",]
student.sort(reverse=True)
print("Descending order",student)
# Descending order ['Akash', 'Dileep', 'farukh', 'shivem', 'suraj']
# [suraj, shivem, farukh, dileep, akash]